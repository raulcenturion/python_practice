# 🔸 Ejemplo:
# for con enumerate() para tener índice y valor
colores = ["rojo", "verde", "azul"]
for i, color in enumerate(colores):
    print(f"{i}: {color}")

# range(inicio, fin, paso)
for num in range(2, 11, 2):
    print(num, end=" ")  # 2 4 6 8 10
print()

