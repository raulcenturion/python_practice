# 🔸 Ejemplo:
# type() te dice el tipo de dato de cualquier valor
numero = 10
decimal = 3.14
texto = "Hola mundo"
activo = True
lista = [1, 2, 3]

print(numero, type(numero))
print(decimal, type(decimal))
print(texto, type(texto))
print(activo, type(activo))
print(lista, type(lista))

